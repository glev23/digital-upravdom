"""Детектор вопроса о правах (RIGHTS-001).

Отрицательные примеры здесь важнее положительных: перехватить жалобу или
вопрос «кому» дороже, чем не распознать вопрос о правах — в первом случае
житель остаётся без заявки.
"""

from __future__ import annotations

import pytest

from upravdom.rights.detect import detect


@pytest.mark.parametrize(
    "message",
    [
        "могут ли отключить горячую воду на месяц?",
        "Могут ли нам отключить свет за долг соседа?",
        "имеют ли право отключить воду без предупреждения?",
        "обязаны ли они предупредить об отключении?",
        "должны ли предупредить о плановом отключении заранее?",
        "положен ли перерасчёт за две недели без отопления?",
        "какой срок устранения аварии по нормативу?",
        "сколько часов можно без холодной воды?",
        "за сколько дней должны предупредить о плановом отключении?",
        "как получить перерасчёт за холодные батареи?",
        "куда жаловаться на управляющую компанию?",
        "вправе ли УК брать плату за это?",
        "законно ли отключать воду должникам?",
        "а могут ли отключить газ зимой?",
        "подскажите, сколько дней можно без лифта?",
    ],
)
def test_rights_questions_are_detected(message: str) -> None:
    question = detect(message)
    assert question is not None
    assert not question.from_command
    assert question.text == message


@pytest.mark.parametrize(
    ("message", "expected"),
    [
        (
            "/права могут ли отключить горячую воду на месяц?",
            "могут ли отключить горячую воду на месяц?",
        ),
        ("/rights какой срок устранения аварии", "какой срок устранения аварии"),
        ("вопрос: положен ли перерасчёт", "положен ли перерасчёт"),
        ("/ПРАВА куда жаловаться", "куда жаловаться"),
    ],
)
def test_commands_are_detected_and_stripped(message: str, expected: str) -> None:
    question = detect(message)
    assert question is not None
    assert question.from_command
    assert question.text == expected


@pytest.mark.parametrize("message", ["/права", "/rights", "  /права   ", "вопрос:"])
def test_command_without_text_asks_for_the_question(message: str) -> None:
    question = detect(message)
    assert question is not None
    assert question.from_command
    assert question.text == ""


@pytest.mark.parametrize(
    "message",
    [
        # Вопрос «кому» — ядро продукта, идёт в классификацию (CLASSIFY-001).
        "кто должен чинить стояк?",
        "кто отвечает за протечку в подвале?",
        "кому звонить при аварии?",
        "куда звонить, если прорвало трубу?",
        "к кому обращаться по поводу лифта?",
        "чья зона ответственности — стояк или квартира?",
        "а кто должен предупредить об отключении?",
        # Описание проблемы, даже с вопросительным знаком.
        "опять нет воды?",
        "из стены за ванной сифонит",
        "это нормально, что батареи ледяные?",
        "у нас третий день нет горячей, когда починят?",
        "лифт не работает, что делать?",
        # Утверждение без вопроса — это жалоба, а не справка.
        "должны были предупредить, но не предупредили",
        "нам обязаны сделать перерасчёт, а не делают",
        # Оборот не в начале — всё ещё жалоба.
        "течёт труба, а обязаны ли они чинить?",
        "",
        "   ",
    ],
)
def test_not_a_rights_question(message: str) -> None:
    assert detect(message) is None
