"""Бытовой диалог до классификации (FLOW-002).

Без этого слоя «спасибо», «ок» и «какой у меня дом» уходили в классификацию:
вызов внешней модели на каждую реплику и заявка диспетчеру на каждое «ага».

**Перехват сознательно узкий: только сообщение целиком.** Ошибки здесь
несимметричны — принять жалобу за болтовню значит потерять проблему жителя,
а пропустить болтовню в классификацию значит лишнюю заявку. Поэтому
«спасибо» перехватывается, а «спасибо, но у меня течёт» — нет: якоря `^...$`
достаточно, отдельный список «проблемных» слов не нужен и был бы хрупким.
Тот же приём и по той же причине выбран в RIGHTS-001 (§6.4).
"""

from __future__ import annotations

import re
from enum import StrEnum


class Intent(StrEnum):
    """Что житель хотел сказать, если это не жалоба."""

    HELP = "help"
    """Что умеет бот и как им пользоваться."""

    HOUSE_INFO = "house_info"
    """Какой дом привязан, как его сменить."""

    SMALLTALK = "smalltalk"
    """Приветствие, благодарность, короткое подтверждение, прощание."""

    JUNK = "junk"
    """Случайный набор символов или сообщение без единого слова."""


_TAIL = r"[\s!.?,)（）\-–—]*"


def _whole(*alternatives: str) -> re.Pattern[str]:
    return re.compile(rf"^(?:{'|'.join(alternatives)}){_TAIL}$", re.IGNORECASE)


_PATTERNS: tuple[tuple[Intent, re.Pattern[str]], ...] = (
    (
        Intent.HELP,
        _whole(
            r"/help",
            r"help",
            r"помощь",
            r"помоги(?:те)?",
            r"справка",
            r"меню",
            r"начать",
            r"инструкция",
            r"что\s+(?:ты\s+)?(?:умеешь|можешь|делаешь)",
            r"(?:а\s+)?что\s+тут\s+можно",
            r"как\s+(?:тобой\s+|этим\s+|ботом\s+)?пользоваться",
            r"как\s+(?:это\s+)?работает",
            r"(?:а\s+)?(?:ты\s+)?кто(?:\s+ты)?",
            r"ты\s+(?:бот|робот|человек)",
            r"зачем\s+ты",
        ),
    ),
    (
        Intent.HOUSE_INFO,
        _whole(
            r"(?:а\s+)?какой\s+(?:у\s+меня\s+)?(?:дом|адрес)(?:\s+привязан)?",
            r"какой\s+дом\s+(?:у\s+меня\s+)?(?:привязан|указан|выбран)",
            r"мой\s+(?:дом|адрес)",
            r"(?:я\s+)?по\s+какому\s+адресу",
            r"мой\s+адрес\s+какой",
            r"что\s+за\s+дом",
            r"как\s+(?:сменить|поменять|изменить|отвязать)\s+(?:дом|адрес)",
            r"это\s+не\s+мой\s+дом",
            r"дом\s+не\s+мой",
        ),
    ),
    (
        Intent.SMALLTALK,
        _whole(
            r"привет(?:ствую)?",
            r"здравствуй(?:те)?",
            r"добрый\s+(?:день|вечер)",
            r"доброе\s+утро",
            r"спасибо(?:\s+большое)?",
            r"благодарю",
            r"спс",
            r"пасибо",
            r"ок(?:ей)?",
            r"ok",
            r"хорошо",
            r"ясно",
            r"понятно",
            r"принято",
            r"да",
            r"нет",
            r"ага",
            r"угу",
            r"пока",
            r"до\s+свидания",
            r"всего\s+доброго",
            r"\+",
        ),
    ),
)

# Слово — хотя бы две буквы подряд: «)))», «?», «12345» словами не являются.
_HAS_WORD = re.compile(r"[а-яёa-z]{2,}", re.IGNORECASE)
# Набор согласных без гласных: «asdasd», «ыва», «джфывл».
_NO_VOWEL = re.compile(r"^[^аеёиоуыэюяaeiouy\W\d]+$", re.IGNORECASE)


def detect(text: str | None) -> Intent | None:
    """Интент бытового диалога или None, если это похоже на обращение.

    None — безопасный ответ по умолчанию: сообщение уходит в классификацию.
    """

    if text is None:
        return None
    normalized = " ".join(text.replace("ё", "е").split())
    if not normalized:
        return None

    for intent, pattern in _PATTERNS:
        if pattern.match(normalized):
            return intent

    if not _HAS_WORD.search(normalized):
        return Intent.JUNK
    # Одно короткое слово без гласных смыслом не обладает; фразу из нескольких
    # слов не трогаем — «нет воды» это жалоба, а не мусор.
    words = normalized.split()
    if len(words) == 1 and len(words[0]) <= 12 and _NO_VOWEL.match(words[0]):
        return Intent.JUNK
    return None
