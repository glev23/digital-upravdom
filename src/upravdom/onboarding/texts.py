def consent_text(version: int, privacy_policy_url: str | None) -> str:
    text = CONSENT_TEXTS[version]
    if privacy_policy_url:
        text += f"\n\nПолитика обработки данных: {privacy_policy_url}"
    return text


def ensure_consent_text(version: int) -> None:
    """Проверка при старте: отсутствие текста — ошибка конфигурации, а не
    пустое сообщение жителю на шаге согласия."""

    if version not in CONSENT_TEXTS:
        raise RuntimeError(f"нет текста согласия для CONSENT_VERSION={version}")
