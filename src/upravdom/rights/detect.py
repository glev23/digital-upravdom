"""Отличить вопрос о правах от жалобы (RIGHTS-001).

Без изменений классификатора: явная команда плюс **узкая** эвристика.
Перехватить лишнее дороже, чем не перехватить: «кто должен чинить стояк» —
это ядро продукта (вопрос «кому»), и увести его в справку по нормативам
значит сломать основной сценарий. Поэтому список оборотов закрытый, а
отрицательные примеры — обязательная часть тестов.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

COMMANDS = ("/rights", "/права", "вопрос:")

# То же самое, но без слеша: житель пишет «права за сколько часов приедет
# мастер», потому что подсказку про команду он видел мельком. Граница слова
# обязательна — иначе «правая батарея не греет» превратилась бы в вопрос о
# правах и осталась без заявки.
_BARE_COMMAND = re.compile(r"^\s*(?:права|право|вопрос)\b[\s:,–—-]*", re.IGNORECASE)
# После голого слова нужен либо разделитель («права: могут ли…»), либо сам
# оборот вопроса — иначе «право собственности на подвал у кого» и «права
# жильцов нарушают, в подъезде темно» ушли бы в справку вместо заявки.
_BARE_DELIMITER = re.compile(r"^\s*(?:права|право|вопрос)\b\s*[:,–—-]", re.IGNORECASE)

# Обороты «кому адресовать» — это классификация, а не справка о правах.
# Проверяются первыми: «кто должен предупредить» начинается с «кто», и без
# этого списка попало бы под «должны ли предупредить».
_NOT_RIGHTS = re.compile(
    r"^\s*(?:а\s+)?(?:кто|кому|куда\s+звонить|к\s+кому|чья|чей|чьё|чье)\b",
    re.IGNORECASE,
)

# Начало фразы — оборот о правах или обязанностях. Якорь на начало намеренно:
# «течёт труба, а обязаны ли они чинить» — это всё ещё жалоба, её надо
# классифицировать и завести заявку.
# Обороты, которые вопросительны по построению: «могут ли…», «за сколько
# дней…». Для них знак вопроса необязателен — без этого житель, который его
# не поставил, получал заявку диспетчеру вместо ответа (живой прогон
# 28.09.2026). Для оборотов вида «сколько часов…» знак вопроса остаётся
# обязательным: «сколько часов уже нет воды» — жалоба, а не справка.
_SELF_EVIDENT_QUESTION = re.compile(
    r"^\s*(?:(?:а|скажите|подскажите|пожалуйста)\s*,?\s+)*"
    r"(?:"
    r"мог[уи]т\s+ли"
    r"|име[юе]т\s+ли\s+прав\w*"
    r"|вправе\s+ли"
    r"|обязан[ыа]?\s+ли"
    r"|должн[ыа]\s+ли"
    r"|положен[оа]?\s+ли"
    r"|законно\s+ли"
    r"|прав\w*\s+ли"
    r"|как(?:ой|ие|ов)\s+срок\w*"
    r"|за\s+сколько\s+(?:дней|часов|суток)"
    r"|как\s+(?:получить|сделать|добиться|оформить)\s+перерасч[её]т"
    r"|куда\s+жаловаться"
    r"|куда\s+обращаться\s+с\s+жалоб\w*"
    r"|имею\s+ли\s+я\s+прав\w*"
    r")\b",
    re.IGNORECASE,
)

_RIGHTS_OPENING = re.compile(
    # Вежливые зачины перед самим оборотом: «подскажите, сколько дней…».
    r"^\s*(?:(?:а|скажите|подскажите|пожалуйста)\s*,?\s+)*"
    r"(?:"
    r"мог[уи]т\s+ли"
    r"|име[юе]т\s+ли\s+прав\w*"
    r"|вправе\s+ли"
    r"|обязан[ыа]?\s+ли"
    r"|должн[ыа]\s+ли"
    r"|положен[оа]?\s+ли"
    r"|законно\s+ли"
    r"|прав\w*\s+ли"
    r"|как(?:ой|ие|ов)\s+срок\w*"
    r"|сколько\s+(?:можно|дней|часов|суток|времени)"
    r"|за\s+сколько\s+(?:дней|часов|суток)"
    r"|как\s+(?:получить|сделать|добиться|оформить)\s+перерасч[её]т"
    r"|куда\s+жаловаться"
    r"|куда\s+обращаться\s+с\s+жалоб\w*"
    r"|имею\s+ли\s+я\s+прав\w*"
    r")\b",
    re.IGNORECASE,
)


@dataclass(slots=True, frozen=True)
class RightsQuestion:
    """`text` пуст — команда без вопроса: жителю нужна подсказка, не поиск."""

    text: str
    from_command: bool


def detect(message: str) -> RightsQuestion | None:
    """None — это не вопрос о правах, сообщение идёт в классификацию."""

    raw = message.strip()
    if not raw:
        return None

    lowered = raw.lower()
    for command in COMMANDS:
        if lowered.startswith(command):
            return RightsQuestion(text=raw[len(command) :].strip(), from_command=True)

    bare = _BARE_COMMAND.match(raw)
    if bare:
        rest = raw[bare.end() :].strip()
        looks_like_question = bool(
            _SELF_EVIDENT_QUESTION.search(rest) or _RIGHTS_OPENING.search(rest)
        )
        if _BARE_DELIMITER.match(raw) or looks_like_question:
            return RightsQuestion(text=rest, from_command=True)

    if _NOT_RIGHTS.search(raw):
        return None
    # Оборот вопросителен сам по себе — знак вопроса необязателен.
    if _SELF_EVIDENT_QUESTION.search(raw):
        return RightsQuestion(text=raw, from_command=False)
    # Остальные обороты («сколько часов…») без знака вопроса неотличимы от
    # жалобы, поэтому для них правило прежнее.
    if "?" not in raw:
        return None
    if _RIGHTS_OPENING.search(raw):
        return RightsQuestion(text=raw, from_command=False)
    return None
