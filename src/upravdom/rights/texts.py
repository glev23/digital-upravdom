"""Тексты справки по нормативам (RIGHTS-001, architecture.md §6.4)."""

from __future__ import annotations

ACK_SEARCHING = "Ищу в нормативах…"

HINT_NO_QUESTION = (
    "Напишите вопрос после команды, например: /права могут ли отключить горячую воду на месяц?"
)

BASIS_HEADER = "Основание:"
DISCLAIMER = "Это справка по нормативам, а не юридическая консультация."

# Отказ, а не частичный ответ: выдуманная норма хуже молчания — житель пойдёт
# с ней в УК или ГЖИ (architecture.md §4, §6.4).
REFUSED = (
    "В нормативах, которые я знаю, прямого ответа на этот вопрос нет. "
    "Вы можете уточнить в своей управляющей компании (АДС: {contact}) "
    "или в жилищной инспекции вашего региона."
)
LLM_UNAVAILABLE = (
    "Сейчас не могу подобрать ответ по нормативам — попробуйте позже. "
    "Если вопрос срочный, позвоните в аварийно-диспетчерскую службу УК: {contact}."
)
NO_CONTACT = "контакт уточнит диспетчер"


def format_answer(answer: str, labels: list[str]) -> str:
    """Ответ + список подтверждённых норм + оговорка.

    Ссылки — полные `label` фрагментов («ПП РФ №354, Прил. 1 п. 4»), а не
    короткий `ref`: без названия акта житель не найдёт норму.
    """

    lines = [answer.strip(), "", BASIS_HEADER]
    lines.extend(f"• {label}" for label in labels)
    lines.extend(["", DISCLAIMER])
    return "\n".join(lines)
